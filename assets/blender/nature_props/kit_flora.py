def _hw_paint(s):
    s = min(max(s, 0.0), 1.0)
    return 0.93 * math.sin(math.pi * max(s, 1e-4) ** 0.78) ** 0.8 * (1 - 0.1 * s)


def _petal(mb, base, ang, length, width, tilt_deg, cup, curl, tex, rows, phase, z_top, twist=0.0):
    radial = np.array([math.cos(ang), math.sin(ang), 0.0])
    tang = np.array([-math.sin(ang), math.cos(ang), 0.0])
    up = np.array([0, 0, 1.0])
    ss_ = np.linspace(0, 1, rows)
    grid = []
    for s in ss_:
        t = math.radians(tilt_deg + curl * s ** 2 * 35.0)
        g = up * math.cos(t) + radial * math.sin(t)
        nrm = np.cross(tang, g)
        nrm /= np.linalg.norm(nrm)
        # centre line integrates the bending direction
        hw_geo = 1.12 * _hw_paint(0.015 + 0.97 * s) + 0.05 if 0 < s < 1 else (0.22 if s == 0 else 0.12)
        row = []
        for q in (-1.0, 0.0, 1.0):
            p = np.array(base) + g * length * s
            p = p + tang * (q * hw_geo * width * 0.5) * math.cos(twist) + nrm * (cup * width * (q * q) * hw_geo)
            u = 0.5 + 0.5 * q * hw_geo * 0.98
            v = 0.015 + 0.97 * s
            h_weight = (p[2] / max(z_top, 1e-3)) ** 1.5 * 0.35
            row.append((mb.vert(p), rect_uv(tex, u, v), wind_uv(h_weight, phase)))
        grid.append(row)
    for r in range(rows - 1):
        for c in range(2):
            a, b, d, e = grid[r][c], grid[r][c + 1], grid[r + 1][c + 1], grid[r + 1][c]
            mb.face([a[0], b[0], d[0], e[0]], [a[1], b[1], d[1], e[1]], [a[2], b[2], d[2], e[2]])


def _ring_mesh(mb, cx, cy, z, r0, r1, z1, n, tex, uv_fn, phase, z_top):
    for k in range(n):
        a0, a1 = 2 * math.pi * k / n, 2 * math.pi * (k + 1) / n
        p = [(cx + r0 * math.cos(a0), cy + r0 * math.sin(a0), z), (cx + r0 * math.cos(a1), cy + r0 * math.sin(a1), z),
             (cx + r1 * math.cos(a1), cy + r1 * math.sin(a1), z1), (cx + r1 * math.cos(a0), cy + r1 * math.sin(a0), z1)]
        idx = [mb.vert(x) for x in p]
        uvs = [uv_fn(k / n, 0), uv_fn((k + 1) / n, 0), uv_fn((k + 1) / n, 1), uv_fn(k / n, 1)]
        w = [wind_uv((x[2] / max(z_top, 1e-3)) ** 1.5 * 0.35, phase) for x in p]
        mb.face(idx, uvs, w)


def _disc(mb, cx, cy, z, r, n, tex, phase, z_top, flip=False):
    c = mb.vert((cx, cy, z))
    ring = [mb.vert((cx + r * math.cos(2 * math.pi * k / n), cy + r * math.sin(2 * math.pi * k / n), z)) for k in range(n)]
    for k in range(n):
        a0, a1 = 2 * math.pi * k / n, 2 * math.pi * (k + 1) / n
        uv = [rect_uv(tex, 0.5, 0.5), rect_uv(tex, 0.5 + 0.46 * math.cos(a0), 0.5 + 0.46 * math.sin(a0)),
              rect_uv(tex, 0.5 + 0.46 * math.cos(a1), 0.5 + 0.46 * math.sin(a1))]
        w = [wind_uv((z / max(z_top, 1e-3)) ** 1.5 * 0.35, phase)] * 3
        idx = [c, ring[k], ring[(k + 1) % n]]
        if flip:
            idx, uv = idx[::-1], uv[::-1]
        mb.face(idx, uv, w)


def _stem(mb, base, top, radius, sides, segs, tex, phase, z_top, bow=0.02):
    base, top = np.array(base, float), np.array(top, float)
    axis = top - base
    side = np.cross(axis, [0, 0, 1.0]) if abs(axis[2]) < 0.99 * np.linalg.norm(axis) else np.array([1.0, 0, 0])
    side /= np.linalg.norm(side) + 1e-9
    rings = []
    for j in range(segs + 1):
        s = j / segs
        c = base + axis * s + side * bow * math.sin(math.pi * s)
        a = axis / np.linalg.norm(axis)
        e1 = np.cross(a, [0, 1.0, 0]) if abs(a[1]) < 0.9 else np.cross(a, [1.0, 0, 0])
        e1 /= np.linalg.norm(e1)
        e2 = np.cross(a, e1)
        row = []
        for k in range(sides):
            th = 2 * math.pi * k / sides
            p = c + radius * (math.cos(th) * e1 + math.sin(th) * e2)
            row.append(mb.vert(p))
        rings.append((row, s, c))
    for j in range(segs):
        r0, s0, c0 = rings[j]
        r1, s1, c1 = rings[j + 1]
        for k in range(sides):
            k1 = (k + 1) % sides
            uv = [rect_uv(tex, s0, k / sides), rect_uv(tex, s0, (k + 1) / sides),
                  rect_uv(tex, s1, (k + 1) / sides), rect_uv(tex, s1, k / sides)]
            w0 = wind_uv(max(0.0, c0[2] / max(z_top, 1e-3)) ** 1.5 * 0.35, phase)
            w1 = wind_uv(max(0.0, c1[2] / max(z_top, 1e-3)) ** 1.5 * 0.35, phase)
            mb.face([r0[k], r0[k1], r1[k1], r1[k]], uv, [w0, w0, w1, w1])


def lotus_lods(spec):
    P = spec["params"]
    col = P["color"]
    phase = (spec["seed"] * 0.137) % 1.0
    out = {}
    for lod in (0, 1, 2):
        mb = MB()
        zt = P["stem_h"]
        top_est = zt + max(r["length"] for r in P["rings"])
        _stem(mb, (0, 0, -0.02), (0.0, 0.0, zt), 0.009, 4 if lod < 2 else 3, 2 if lod == 0 else 1, "stem", phase,
              top_est, bow=P.get("bow", 0.015))
        rings = P["rings"] if lod == 0 else (P["rings"][:1] if lod == 2 else P["rings"])
        for ri, rg in enumerate(rings):
            n = rg["count"] if lod == 0 else max(4, rg["count"] - (2 if lod == 1 else 3))
            rows = 3 if lod < 2 else 2
            for k in range(n):
                a = 2 * math.pi * (k + 0.5 * ri) / n + rg.get("offset", 0.0)
                tex = f"petal_{col}_{rg['tex']}"
                jit = 1.0 + 0.06 * math.sin(k * 2.3 + ri)
                base = (0.012 * math.cos(a) * (1 + ri * 0.2), 0.012 * math.sin(a) * (1 + ri * 0.2), zt - 0.004 + 0.004 * ri)
                _petal(mb, base, a, rg["length"] * jit, rg["width"], rg["tilt"] + 4 * math.sin(k * 1.7), rg["cup"],
                       rg.get("curl", 0.3), tex, rows, phase, top_est)
        if P.get("open", True) and lod < 2:
            pr, ph = P["pod_r"], P["pod_h"]
            _ring_mesh(mb, 0, 0, zt, pr * 0.65, pr, zt + ph, 8 if lod == 0 else 6, "pod_side",
                       lambda u, v: rect_uv("pod_side", u, v), phase, top_est)
            _disc(mb, 0, 0, zt + ph, pr, 8 if lod == 0 else 6, "pod_top", phase, top_est)
            if lod == 0:
                _ring_mesh(mb, 0, 0, zt + ph * 0.6, pr * 1.02, pr * 1.75, zt + ph + P.get("stamen_h", 0.025), 8,
                           "stamens", lambda u, v: rect_uv("stamens", u, v), phase, top_est)
        if P.get("leaf") and lod < 2:
            lf = P["leaf"]
            mb2 = mb
            n = 12 if lod == 0 else 8
            c = mb2.vert((lf["x"], lf["y"], 0.006))
            ring = []
            for k in range(n):
                a = 2 * math.pi * k / n
                ring.append(mb2.vert((lf["x"] + lf["r"] * math.cos(a), lf["y"] + lf["r"] * math.sin(a),
                                      0.006 + lf.get("cup", 0.02) * (1 + 0.3 * math.sin(a * 3)))))
            for k in range(n):
                a0, a1 = 2 * math.pi * k / n, 2 * math.pi * (k + 1) / n
                uv = [rect_uv("lotus_leaf", 0.5, 0.5), rect_uv("lotus_leaf", 0.5 + 0.47 * math.cos(a0), 0.5 + 0.47 * math.sin(a0)),
                      rect_uv("lotus_leaf", 0.5 + 0.47 * math.cos(a1), 0.5 + 0.47 * math.sin(a1))]
                mb2.face([c, ring[k], ring[(k + 1) % n]], uv, [wind_uv(0, phase)] + [wind_uv(0.06, phase)] * 2)
        out[f"lod{lod}"] = mb.build(f"{spec['id']}__lod{lod}")
    return out


# --------------------------------------------------------------------------------------------- reeds

def _card(mb, base, yaw, width, height, bend, tex, phase, rows=4, lean=0.0):
    d = np.array([math.cos(yaw), math.sin(yaw), 0.0])      # card plane direction (across)
    n = np.array([-math.sin(yaw), math.cos(yaw), 0.0])      # bend direction (card normal)
    grid = []
    for j in range(rows):
        s = j / (rows - 1)
        c = np.array(base) + np.array([0, 0, height * s]) + n * (bend * s ** 2) + d * (lean * s)
        c[2] -= abs(bend) * 0.25 * s ** 2                      # bending shortens the card a little
        row = []
        for q in (-0.5, 0.5):
            p = c + d * width * q
            row.append((mb.vert(p), rect_uv(tex, q + 0.5, s), wind_uv(s ** 1.3, phase)))
        grid.append(row)
    for j in range(rows - 1):
        a, b, c2, e = grid[j][0], grid[j][1], grid[j + 1][1], grid[j + 1][0]
        mb.face([a[0], b[0], c2[0], e[0]], [a[1], b[1], c2[1], e[1]], [a[2], b[2], c2[2], e[2]])


def _cattail(mb, base, height, phase, sides=6, head_len=0.13, head_r=0.024, lean=(0.0, 0.0)):
    top = (base[0] + lean[0], base[1] + lean[1], height)
    _stem(mb, base, (base[0] + lean[0] * 0.86, base[1] + lean[1] * 0.86, height - head_len - 0.01), 0.006,
          3 if sides <= 4 else 4, 2, "stem_reed", phase, height, bow=0.01)
    hb = np.array([base[0] + lean[0] * 0.87, base[1] + lean[1] * 0.87, height - head_len - 0.01])
    ht = np.array([base[0] + lean[0] * 0.98, base[1] + lean[1] * 0.98, height - 0.015])
    rings = []
    for z, c, rf in ((0, hb, 0.85), (1, hb + (ht - hb) * 0.5, 1.0), (2, ht, 0.8)):
        row = [mb.vert(c + np.array([head_r * rf * math.cos(2 * math.pi * k / sides),
                                      head_r * rf * math.sin(2 * math.pi * k / sides), 0])) for k in range(sides)]
        rings.append((row, z / 2.0, c))
    for j in range(2):
        r0, s0, c0 = rings[j]
        r1, s1, c1 = rings[j + 1]
        for k in range(sides):
            k1 = (k + 1) % sides
            uv = [rect_uv("cattail", k / sides, s0), rect_uv("cattail", (k + 1) / sides, s0),
                  rect_uv("cattail", (k + 1) / sides, s1), rect_uv("cattail", k / sides, s1)]
            w = [wind_uv(max(0.0, c0[2] / height) ** 1.3, phase)] * 2 + [wind_uv(max(0.0, c1[2] / height) ** 1.3, phase)] * 2
            mb.face([r0[k], r0[k1], r1[k1], r1[k]], uv, w)
    # caps + spike
    for row, c, sgn in ((rings[0][0], hb, -1), (rings[2][0], ht, 1)):
        cc = mb.vert(c + np.array([0, 0, 0.004 * sgn]))
        for k in range(sides):
            k1 = (k + 1) % sides
            idx = [cc, row[k1], row[k]] if sgn < 0 else [cc, row[k], row[k1]]
            mb.face(idx, [rect_uv("cattail", 0.5, 0.95 if sgn > 0 else 0.05)] * 3, [wind_uv(1.0, phase)] * 3)
    tip = mb.vert((top[0], top[1], height + 0.07))
    for k in range(sides):
        k1 = (k + 1) % sides
        mb.face([rings[2][0][k], rings[2][0][k1], tip], [rect_uv("stem_reed", 0.9, 0.2), rect_uv("stem_reed", 0.9, 0.6),
                                                       rect_uv("stem_reed", 1.0, 0.4)], [wind_uv(1.0, phase)] * 3)


def reeds_lods(spec):
    P = spec["params"]
    rng0 = np.random.default_rng(spec["seed"])
    cards = []
    for i in range(P["cards"]):
        r = P["radius"] * math.sqrt(rng0.uniform(0.05, 1))
        a = rng0.uniform(0, 2 * math.pi)
        cards.append(dict(base=(r * math.cos(a), r * math.sin(a), -0.03), yaw=rng0.uniform(0, math.pi),
                          width=rng0.uniform(*P["width"]), height=rng0.uniform(*P["height"]),
                          bend=rng0.uniform(-1, 1) * P["bend"], tex=P["tex"][i % len(P["tex"])],
                          phase=(0.6180339887 * (i + 1) + spec["seed"] * 0.137) % 1.0,
                          lean=rng0.uniform(-0.06, 0.06)))
    cards.sort(key=lambda c: -c["height"])
    cats = []
    for j in range(P.get("cattails", 0)):
        a = rng0.uniform(0, 2 * math.pi)
        r = P["radius"] * 0.6 * math.sqrt(rng0.uniform(0, 1))
        cats.append(dict(base=(r * math.cos(a), r * math.sin(a), -0.03), height=rng0.uniform(*P["cattail_h"]),
                         lean=(rng0.uniform(-0.08, 0.08), rng0.uniform(-0.08, 0.08)),
                         phase=(0.37 * (j + 1) + spec["seed"] * 0.11) % 1.0))
    out = {}
    for lod in (0, 1, 2):
        mb = MB()
        cl = cards if lod == 0 else (cards[: max(3, len(cards) // 2 + 1)] if lod == 1 else cards[:2])
        for c in cl:
            w = c["width"] * (1.0 if lod == 0 else (1.15 if lod == 1 else 1.4))
            _card(mb, c["base"], c["yaw"] if lod < 2 else c["yaw"], w, c["height"], c["bend"], c["tex"], c["phase"],
                  rows=4 if lod == 0 else 3, lean=c["lean"])
        if lod == 2 and len(cl) >= 2:
            pass
        ct = cats if lod < 2 else cats[:1]
        for c in ct:
            _cattail(mb, c["base"], c["height"], c["phase"], sides=6 if lod == 0 else (4 if lod == 1 else 3),
                     lean=c["lean"])
        out[f"lod{lod}"] = mb.build(f"{spec['id']}__lod{lod}")
    return out


