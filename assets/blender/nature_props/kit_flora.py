"""Water-edge flora kit (P1): 3 lily pad variants, lotus bud/open in pink and white, 3 reed/cattail clumps.

Recipes (seeded, parametric, LOD0-2 generated by the same recipe at lower detail):
  flora.lilypad/1  floating pads: fan disc with a notch (sinus), cupped rim, edge wave, optional curled young pad
  flora.lotus/1    petal-ring recipe: rings of curved 12-triangle petals (count, length, width, tilt, cup, curl),
                   seed pod frustum + stamen ring card, curved stem, optional floating lotus leaf; bud = closed rings
  flora.reeds/1    clump of bent vertical blade cards (several painted blades per card) + cattail stems and heads
UV0 maps into the painted atlas sm_flora_water (flora_layout.WATER). UV1 'wind' = TEXCOORD_1 for nature-motion.ts
uv2 mode: x = sway weight (0 at the water/ground, 1 at the tips), y stored as 1 - phase (exporter flips v).
Alpha-tested (cutoff 0.5) double-sided material, foliage profile. Pivot: water surface / ground contact at y = 0.
"""
from __future__ import annotations

