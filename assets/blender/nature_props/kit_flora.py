def _pad(mb, cx, cy, r, rot, tex, seg, notch_deg, cup, wave, rings, phase, z0=0.004, lift=0.0, curl=0.0):
    half = math.radians(notch_deg) / 2
    c = mb.vert((cx, cy, z0 + lift))
    angs = np.linspace(half, 2 * math.pi - half, seg + 1)
    radii = [0.55, 1.0] if rings == 2 else [1.0]
    ring_idx = []
    for rf in radii:
        row = []
        for a in angs:
            rr = r * rf
            lx, ly = rr * math.cos(a), rr * math.sin(a)
            z = z0 + lift + cup * rf ** 2.2 + wave * math.sin(a * 5 + phase * 6.28) * rf ** 2
            if curl > 0:   # young pad: one side rolls up
                z += curl * max(0.0, math.cos(a - math.pi)) ** 2 * rf ** 1.5
            x = cx + lx * math.cos(rot) - ly * math.sin(rot)
            y = cy + lx * math.sin(rot) + ly * math.cos(rot)
            row.append((mb.vert((x, y, z)), (lx / r, ly / r), rf))
        ring_idx.append(row)

    def uvp(lxy):
        return rect_uv(tex, 0.5 + 0.47 * lxy[0] / 0.98 * 0.98, 0.5 + 0.47 * lxy[1])

    wc = wind_uv(0.0, phase)
    inner = ring_idx[0]
    for k in range(seg):
        a, b = inner[k], inner[k + 1]
        mb.face([c, a[0], b[0]], [uvp((0, 0)), uvp(a[1]), uvp(b[1])],
                [wc, wind_uv(0.05 * a[2], phase), wind_uv(0.05 * b[2], phase)])
    if len(ring_idx) == 2:
        outer = ring_idx[1]
        for k in range(seg):
            a, b, d, e = inner[k], inner[k + 1], outer[k + 1], outer[k]
            mb.face([a[0], e[0], d[0], b[0]], [uvp(a[1]), uvp(e[1]), uvp(d[1]), uvp(b[1])],
                    [wind_uv(0.05 * a[2], phase), wind_uv(0.08, phase), wind_uv(0.08, phase), wind_uv(0.05 * b[2], phase)])


def lilypad_lods(spec):
    P = spec["params"]
    out = {}
    for lod, seg, rings in ((0, P.get("seg", 12), 2), (1, 8, 1), (2, 6, 1)):
        mb = MB()
        for i, pd in enumerate(P["pads"]):
            _pad(mb, pd["x"], pd["y"], pd["r"], math.radians(pd["rot"]), pd["tex"], seg if not pd.get("young") else max(6, seg - 4),
                 pd.get("notch", 28.0), pd.get("cup", 0.012), pd.get("wave", 0.004), rings,
                 phase=(0.618 * (i + 1) + spec["seed"] * 0.137) % 1.0, lift=pd.get("lift", 0.0), curl=pd.get("curl", 0.0))
        out[f"lod{lod}"] = mb.build(f"{spec['id']}__lod{lod}")
    return out


