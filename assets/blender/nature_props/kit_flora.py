import flora_layout as FL
import np_lib as L

KIT = "flora"
ATLASES = [{"id": "sm_flora_water", "albedo_px": 1024, "data_px": 512, "orm_px": 256, "palette": None,
            "budget_class": "bush_lod0", "profile": "foliage", "painted": True,
            "material": {"alpha_clip": 0.5, "double_sided": True}}]
LAY = FL.WATER


class MB:
    """Mesh builder with per-corner UV0 and wind UV1."""

    def __init__(self):
        self.v, self.f, self.uv, self.wind = [], [], [], []

    def vert(self, p):
        self.v.append(tuple(float(x) for x in p))
        return len(self.v) - 1

    def face(self, idx, uvs, winds):
        self.f.append(list(idx))
        self.uv.extend([tuple(u) for u in uvs])
        self.wind.extend([tuple(w) for w in winds])

    def build(self, name):
        ob = L.mesh_from_arrays(name, np.array(self.v), self.f)
        me = ob.data
        if len(me.loops) != len(self.uv):
            raise ValueError('Recipe validation changed corner count; UV/wind data cannot be assigned safely')
        uv0 = me.uv_layers.new(name="UVMap")
        uv1 = me.uv_layers.new(name="wind")
        # from_pydata keeps face corner order, so loops follow self.uv order
        uv0.data.foreach_set("uv", np.array(self.uv, dtype=np.float32).ravel())
        uv1.data.foreach_set("uv", np.array(self.wind, dtype=np.float32).ravel())
        me.uv_layers.active = uv0
        L.set_smooth(ob)
        return ob


def rect_uv(name, u, v):
    """u, v in 0..1 inside the named atlas rect (v up) -> atlas UV."""
    u0, v0, du, dv = FL.uv_rect(LAY, name)
    return (u0 + du * u, v0 + dv * v)


def wind_uv(weight, phase):
    return (float(np.clip(weight, 0, 1)), float(1.0 - np.clip(phase, 0, 0.999)))


